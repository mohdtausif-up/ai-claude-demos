<section class="container prose stack section-pad">
    <h1>Privacy</h1>
    <p>Invite.com is built to collect as little as possible and to keep guest information with the host who invited them.</p>
    <h2>What guests share</h2>
    <p>A guest gives a name and, only if the host asks, an email address or phone number, plus their RSVP and any answers to the host's questions. Fields are marked optional where they are optional. Guests never need an account.</p>
    <h2>Who can see it</h2>
    <p>Only the host and the people they add as collaborators. Guest lists are hidden from other guests unless the host chooses otherwise. We do not sell contact details and we do not send marketing messages to guests.</p>
    <h2>Your control</h2>
    <ul>
        <li>Guests can change their response, or delete their personal data, from their personal link at any time.</li>
        <li>Every email has an unsubscribe link.</li>
        <li>Hosts can export their data and delete an event. Deleted events are recoverable for 30 days, then permanently removed.</li>
        <li>Public search-engine indexing of an invitation is off unless the host turns it on.</li>
    </ul>
    <h2>Security</h2>
    <p>Private links are signed and revocable, passwords are hashed with Argon2id, and sensitive actions are recorded in an audit log.</p>
